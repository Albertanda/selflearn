"""ASR-R1 asynchronous job routes (CONTRACTS D3/D6).

All routes resolve a registered subject in the current user's workspace.  The
POST handler streams the multipart parts into private staging, records the job
and returns 202 without waiting for ffprobe, segmentation or the provider.  A
missing job/foreign subject is a 404; a malformed id is a 400.  GET handlers are
strictly read-only.

The historical C02 ``ErrorCode`` table is frozen and asserted exactly by the
Phase-1 tests, so the ASR-only codes live in ``AsrErrorCode``.  This router
projects them through the same ``{detail, error:{code,message,retryable}}``
envelope before they reach the generic subject error boundary.
"""

from __future__ import annotations

from fastapi import APIRouter, Depends, File, Form, Query, UploadFile
from fastapi.responses import JSONResponse

from deeptutor.api.routers.auth import require_auth
from deeptutor.api.subject_route import SubjectRoute
from deeptutor.services.asr.jobs import AsrJobService
from deeptutor.subjects.errors import AsrOperationError, to_http_payload

router = APIRouter(route_class=SubjectRoute)


def _envelope(job) -> dict:
    return {"operation": "transcribe", "job": job.to_dict()}


def _failure(exc: AsrOperationError) -> JSONResponse:
    return JSONResponse(status_code=exc.http_status, content=to_http_payload(exc))


@router.post("/{subject_id}/asr/jobs", status_code=202)
async def create_asr_job(
    subject_id: str,
    files: list[UploadFile] = File(...),
    request_id: str = Form(...),
    language: str = Form("zh"),
    _: None = Depends(require_auth),
):
    """Stream a recording batch to private staging, then return 202.

    The UUID4 request id is generated by the browser before the upload starts;
    ``job_id`` is its 32-char hex form.  Re-posting the same id with the same
    bytes/language/config returns the same job; different bytes are 409.
    """
    try:
        service = AsrJobService(subject_id)
        view, _created = await service.create_job(
            files, request_id=request_id, language=language
        )
        return JSONResponse(status_code=202, content=_envelope(view))
    except AsrOperationError as exc:
        return _failure(exc)


@router.get("/{subject_id}/asr/jobs")
async def list_asr_jobs(
    subject_id: str,
    limit: int = Query(20, ge=1, le=50),
    _: None = Depends(require_auth),
):
    try:
        service = AsrJobService(subject_id)
        return {"jobs": [view.to_dict() for view in service.list_jobs(limit=limit)]}
    except AsrOperationError as exc:
        return _failure(exc)


@router.get("/{subject_id}/asr/jobs/{job_id}")
async def get_asr_job(
    subject_id: str,
    job_id: str,
    _: None = Depends(require_auth),
):
    try:
        service = AsrJobService(subject_id)
        return _envelope(service.get_job(job_id))
    except AsrOperationError as exc:
        return _failure(exc)


@router.get("/{subject_id}/asr/jobs/{job_id}/result")
async def get_asr_result(
    subject_id: str,
    job_id: str,
    _: None = Depends(require_auth),
):
    try:
        service = AsrJobService(subject_id)
        return service.get_result(job_id)
    except AsrOperationError as exc:
        return _failure(exc)


@router.post("/{subject_id}/asr/jobs/{job_id}/cancel")
async def cancel_asr_job(
    subject_id: str,
    job_id: str,
    _: None = Depends(require_auth),
):
    try:
        service = AsrJobService(subject_id)
        view, changed = await service.cancel_job(job_id)
        status = 202 if changed or view.status != "cancelled" else 200
        return JSONResponse(status_code=status, content=_envelope(view))
    except AsrOperationError as exc:
        return _failure(exc)


@router.post("/{subject_id}/asr/jobs/{job_id}/retry")
async def retry_asr_job(
    subject_id: str,
    job_id: str,
    _: None = Depends(require_auth),
):
    try:
        service = AsrJobService(subject_id)
        view, _started = await service.retry_job(job_id)
        return JSONResponse(status_code=202, content=_envelope(view))
    except AsrOperationError as exc:
        return _failure(exc)


__all__ = ["router"]
